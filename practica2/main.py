def conectar_wifi():
    wlan = network.WLAN(network.STA_IF)
    wlan.active(True)
    wlan.connect(SSID, PASSWORD)

    print("Conectando a WiFi...", end="")
    while not wlan.isconnected():
        print(".", end="")
        utime.sleep(0.3)

    print("\nWiFi conectado")
    print("IP del ESP32:", wlan.ifconfig()[0])
    return wlan

def iniciar_udp():
    addr = socket.getaddrinfo("0.0.0.0", UDP_PORT)[0][-1]
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.bind(addr)
    sock.settimeout(0.1)
    print("Servidor UDP escuchando en puerto", UDP_PORT)
    return sock

def iniciar_multicast():
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    return sock

def enviar_multicast(sock_multi, mensaje):
    try:
        sock_multi.sendto(mensaje.encode("utf-8"), (MULTICAST_GROUP, MULTICAST_PORT))
        print("Multicast enviado ->", mensaje)
    except Exception as e:
        print("Error multicast:", e)

def procesar_mensaje(mensaje):
    mensaje = mensaje.strip().upper()

    if mensaje == "LED_ON":
        led.value(1)
        return "ACK:LED_ON"

    elif mensaje == "LED_OFF":
        led.value(0)
        return "ACK:LED_OFF"

    elif mensaje == "STATUS":
        estado = "ON" if led.value() else "OFF"
        return "STATUS:LED={}".format(estado)

    else:
        return "ERROR:COMANDO_DESCONOCIDO"

def obtener_temperatura():
    sensor.measure()
    temp = sensor.temperature()
    hum = sensor.humidity()
    return temp, hum


def mostrar_emoji(temp, hum):
    oled.fill(0)
    oled.text("Temp: {:.1f}C".format(temp), 0, 0)
    oled.text("Hum: {:.1f}%".format(hum), 0, 10)

    if temp < 15:
        oled.text("FRIO [*]", 30, 30)
    elif temp >= 15 and temp <= 30:
        oled.text("NORMAL :)", 30, 30)
    else:
        oled.text("CALOR [!]", 30, 30)

    estado_led = "ON" if led.value() else "OFF"
    oled.text("LED: {}".format(estado_led), 0, 50)

    oled.show()

def main():
    wlan = conectar_wifi()
    sock = iniciar_udp()
    sock_multi = iniciar_multicast()

    ultimo_update = utime.ticks_ms()
    intervalo_display = 2000  # ms

    while True:
        # 1. Revisar si llegó un mensaje UDP unicast
        try:
            data, remote_addr = sock.recvfrom(1024)
            mensaje = data.decode("utf-8")
            print("Mensaje recibido desde", remote_addr, "->", mensaje)

            respuesta = procesar_mensaje(mensaje)
            sock.sendto(respuesta.encode("utf-8"), remote_addr)

        except OSError:
            pass

        # 2. Actualizar pantalla/sensor cada 2 segundos y enviar multicast
        if utime.ticks_diff(utime.ticks_ms(), ultimo_update) >= intervalo_display:
            try:
                temperatura, humedad = obtener_temperatura()
                mostrar_emoji(temperatura, humedad)

                mensaje_multi = "EVENT:TEMP={:.1f};HUM={:.1f}".format(temperatura, humedad)
                enviar_multicast(sock_multi, mensaje_multi)

            except OSError:
                oled.fill(0)
                oled.text("Error Sensor!", 20, 20)
                oled.text("LED: {}".format("ON" if led.value() else "OFF"), 20, 40)
                oled.show()

            ultimo_update = utime.ticks_ms()

if __name__ == "__main__":
    main()
